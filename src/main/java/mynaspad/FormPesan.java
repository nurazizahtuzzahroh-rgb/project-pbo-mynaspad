    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        MenuNaspad menu = (MenuNaspad) cmbMenu.getSelectedItem();
        if (menu == null) {
            JOptionPane.showMessageDialog(this, "Belum ada menu. Isi data menu di database terlebih dahulu.");
            return;
        }
        int jumlah = (Integer) spnJumlah.getValue();
        int sudahDipesan = pesanan.getJumlahMenu(menu.getKodeMenu());

        // memakai method isTersedia() dari interface KetersediaanMenu
        if (!menu.isTersedia(sudahDipesan + jumlah)) {
            JOptionPane.showMessageDialog(this,
                    "Stok " + menu.getNamaMenu() + " tidak mencukupi!\n"
                    + "Stok tersedia: " + menu.getStok() + ", sudah di keranjang: " + sudahDipesan);
            return;
        }
        pesanan.tambahItem(menu, jumlah);
        spnJumlah.setValue(1);
        refreshKeranjang();
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        int baris = tblKeranjang.getSelectedRow();
        if (baris < 0) {
            JOptionPane.showMessageDialog(this, "Pilih item pada keranjang terlebih dahulu!");
            return;
        }
        pesanan.hapusItem(baris);
        refreshKeranjang();
    }//GEN-LAST:event_btnHapusActionPerformed

    private void btnProsesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnProsesActionPerformed
        String nama = txtPelanggan.getText().trim();
        if (nama.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama pelanggan harus diisi!");
            txtPelanggan.requestFocus();
            return;
        }
        if (pesanan.isKosong()) {
            JOptionPane.showMessageDialog(this, "Keranjang masih kosong!");
            return;
        }
        double bayar;
        try {
            bayar = Double.parseDouble(txtBayar.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Uang bayar harus berupa angka!");
            txtBayar.requestFocus();
            return;
        }
        if (bayar < pesanan.hitungTotal()) {
            JOptionPane.showMessageDialog(this, "Uang bayar kurang dari total pesanan!");
            return;
        }

        try {
            pesanan.setNamaPelanggan(nama);
            int idPesanan = pesananDAO.simpan(pesanan, bayar);
            tampilkanStruk(pesanan.buatStruk(idPesanan, bayar));
            kosongkanForm();
            muatMenu(); // stok di database sudah berkurang
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan pesanan: " + e.getMessage());
            muatMenu();
        }
    }//GEN-LAST:event_btnProsesActionPerformed

    private void btnResetActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResetActionPerformed
        kosongkanForm();
    }//GEN-LAST:event_btnResetActionPerformed

    /** Pengaturan komponen yang tidak tersedia di palette Design (model tabel, spinner, listener). */
    private void siapkanKomponen() {
        setLocationRelativeTo(null);

        modelKeranjang = new DefaultTableModel(
                new String[]{"Kode", "Menu", "Harga", "Jumlah", "Subtotal"}, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        tblKeranjang.setModel(modelKeranjang);
        tblKeranjang.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);

        spnJumlah.setModel(new SpinnerNumberModel(1, 1, 99, 1));

        // kembalian dihitung otomatis setiap uang bayar berubah
        txtBayar.getDocument().addDocumentListener(new DocumentListener() {
            @Override
            public void insertUpdate(DocumentEvent e) {
                hitungKembalian();
            }

            @Override
            public void removeUpdate(DocumentEvent e) {
                hitungKembalian();
            }

            @Override
            public void changedUpdate(DocumentEvent e) {
                hitungKembalian();
            }
        });
    }

    /** INPUT: memuat daftar menu dari database ke combo box. */
    private void muatMenu() {
        try {
            List<MenuNaspad> daftar = menuDAO.getSemuaMenu();
            sedangMemuat = true;
            cmbMenu.removeAllItems();
            for (MenuNaspad m : daftar) {
                cmbMenu.addItem(m);
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat menu: " + e.getMessage());
        } finally {
            sedangMemuat = false;
        }
        tampilkanDetailMenu();
    }

    private void tampilkanDetailMenu() {
        if (sedangMemuat) {
            return;
        }
        MenuNaspad m = (MenuNaspad) cmbMenu.getSelectedItem();
        if (m == null) {
            txtHarga.setText("");
            txtStok.setText("");
            lblJumlah.setText("Jumlah");
            return;
        }
        txtHarga.setText(rupiah.format(m.getHarga()));
        txtStok.setText(String.valueOf(m.getStok()));
        // getInfoMenu() dan getSatuan() berbeda tiap subclass (polymorphism)
        lblJumlah.setText("Jumlah (" + m.getSatuan() + ")");
    }

    /** OUTPUT: menampilkan keranjang dan total. */
    private void refreshKeranjang() {
        modelKeranjang.setRowCount(0);
        for (ItemPesanan item : pesanan.getDaftarItem()) {
            MenuNaspad m = item.getMenu();
            modelKeranjang.addRow(new Object[]{
                m.getKodeMenu(), m.getNamaMenu(), rupiah.format(m.getHarga()),
                item.getJumlah() + " " + m.getSatuan(), rupiah.format(item.getSubtotal())
            });
        }
        txtTotal.setText(rupiah.format(pesanan.hitungTotal()));
        hitungKembalian();
    }

    /** PROSES: menghitung kembalian dari uang bayar. */
    private void hitungKembalian() {
        String teks = txtBayar.getText().trim();
        if (teks.isEmpty()) {
            txtKembali.setText("");
            return;
        }
        try {
            double bayar = Double.parseDouble(teks);
            double kembali = pesanan.hitungKembalian(bayar);
            if (kembali < 0) {
                txtKembali.setText("Kurang " + rupiah.format(-kembali));
            } else {
                txtKembali.setText(rupiah.format(kembali));
            }
        } catch (NumberFormatException e) {
            txtKembali.setText("Input tidak valid");
        }
    }

    private void kosongkanForm() {
        pesanan = new Pesanan();
        txtPelanggan.setText("");
        txtBayar.setText("");
        spnJumlah.setValue(1);
        refreshKeranjang();
    }

    private void tampilkanStruk(String isiStruk) {
        JTextArea area = new JTextArea(isiStruk);
        area.setFont(new Font(Font.MONOSPACED, Font.PLAIN, 12));
        area.setEditable(false);
        JScrollPane sp = new JScrollPane(area);
        sp.setPreferredSize(new Dimension(380, 340));
        JOptionPane.showMessageDialog(this, sp, "Struk Pesanan", JOptionPane.INFORMATION_MESSAGE);
    }

